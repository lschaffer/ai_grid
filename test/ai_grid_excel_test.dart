void main() {
  Uint8List buildMockMultiSheetExcelBytes() {
    final sheet1Xml = '''<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">
  <sheetData>
    <row r="1">
      <c r="A1" t="s"><v>0</v></c>
      <c r="B1" t="s"><v>1</v></c>
      <c r="C1" t="s"><v>2</v></c>
    </row>
    <row r="2">
      <c r="A2" t="s"><v>3</v></c>
      <c r="B2" s="1"><v>45658</v></c>
      <c r="C2"><v>12500.5</v></c>
    </row>
  </sheetData>
</worksheet>''';

    final sheet2Xml = '''<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">
  <sheetData>
    <row r="1">
      <c r="A1" t="s"><v>4</v></c>
      <c r="B1" t="s"><v>5</v></c>
    </row>
    <row r="2">
      <c r="A2" t="s"><v>6</v></c>
      <c r="B2"><v>50000</v></c>
    </row>
  </sheetData>
</worksheet>''';

    final sharedStringsXml =
        '''<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<sst xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" count="7" uniqueCount="7">
  <si><t>Region</t></si>
  <si><t>Date</t></si>
  <si><t>Revenue</t></si>
  <si><t>North America</t></si>
  <si><t>Department</t></si>
  <si><t>Budget</t></si>
  <si><t>Engineering</t></si>
</sst>''';

    final stylesXml = '''<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<styleSheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">
  <cellXfs count="2">
    <xf numFmtId="0"/>
    <xf numFmtId="14"/>
  </cellXfs>
</styleSheet>''';

    final workbookXml =
        '''<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<workbook xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships">
  <sheets>
    <sheet name="Quarterly Sales" sheetId="1" r:id="rId1"/>
    <sheet name="Annual Targets" sheetId="2" r:id="rId2"/>
  </sheets>
</workbook>''';

    final relsXml = '''<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">
  <Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/worksheet" Target="worksheets/sheet1.xml"/>
  <Relationship Id="rId2" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/worksheet" Target="worksheets/sheet2.xml"/>
</Relationships>''';

    final files = <String, List<int>>{
      'xl/workbook.xml': utf8.encode(workbookXml),
      'xl/_rels/workbook.xml.rels': utf8.encode(relsXml),
      'xl/sharedstrings.xml': utf8.encode(sharedStringsXml),
      'xl/styles.xml': utf8.encode(stylesXml),
      'xl/worksheets/sheet1.xml': utf8.encode(sheet1Xml),
      'xl/worksheets/sheet2.xml': utf8.encode(sheet2Xml),
    };

    final archive = Archive();
    for (final entry in files.entries) {
      archive.addFile(ArchiveFile(entry.key, entry.value.length, entry.value));
    }
    return Uint8List.fromList(ZipEncoder().encode(archive));
  }

  group('AiGridExcelParser Tests', () {
    test('Roundtrip: Parses .xlsx generated by fitGridToXlsx', () {
      final exportData = FitGridExportData(
        headers: ['Order ID', 'Product', 'Sales', 'Quantity', 'In Stock'],
        rows: [
          const FitGridExportRow(
            cells: ['ORD-001', 'Ergonomic Desk Chair', '349.99', '2', 'true'],
          ),
          const FitGridExportRow(
            cells: ['ORD-002', 'Wireless Keyboard', '89.50', '5', 'true'],
          ),
          const FitGridExportRow(
            cells: ['ORD-003', 'USB-C Cable Pack', '19.99', '12', 'false'],
          ),
        ],
      );

      final bytes = fitGridToXlsx(exportData, sheetName: 'Orders');
      expect(bytes, isNotEmpty);

      final workbook = AiGridExcelParser.parseBytes(
        bytes,
        fileName: 'orders.xlsx',
      );

      expect(workbook.sheets.length, 1);
      final sheet = workbook.primarySheet;
      expect(sheet, isNotNull);
      expect(sheet!.name, 'Orders');
      expect(sheet.rowCount, 3);
      expect(sheet.columnCount, 5);

      // Verify headers
      expect(sheet.headers, [
        'Order ID',
        'Product',
        'Sales',
        'Quantity',
        'In Stock',
      ]);

      // Verify row values
      expect(sheet.rows[0]['order_id'], 'ORD-001');
      expect(sheet.rows[0]['product'], 'Ergonomic Desk Chair');
      expect(sheet.rows[0]['sales'], 349.99);
      expect(sheet.rows[0]['quantity'], 2);

      // Verify column types inferred
      final salesCol = sheet.columns.firstWhere((c) => c.field == 'sales');
      expect(salesCol.type, AiGridColumnType.number);
      final qtyCol = sheet.columns.firstWhere((c) => c.field == 'quantity');
      expect(qtyCol.type, AiGridColumnType.number);
    });

    test('Parses multi-sheet workbook with shared strings and dates', () {
      final zipBytes = buildMockMultiSheetExcelBytes();
      final workbook = AiGridExcelParser.parseBytes(
        zipBytes,
        fileName: 'enterprise.xlsx',
      );

      expect(workbook.sheets.length, 2);
      expect(workbook.isMultiSheet, isTrue);

      final sheet1 = workbook.getSheet('Quarterly Sales');
      expect(sheet1, isNotNull);
      expect(sheet1!.headers, ['Region', 'Date', 'Revenue']);
      expect(sheet1.rows.length, 1);
      expect(sheet1.rows[0]['region'], 'North America');
      expect(sheet1.rows[0]['revenue'], 12500.5);
      // Date should be converted to YYYY-MM-DD
      expect(sheet1.rows[0]['date'], matches(RegExp(r'^\d{4}-\d{2}-\d{2}$')));

      final sheet2 = workbook.getSheet('Annual Targets');
      expect(sheet2, isNotNull);
      expect(sheet2!.headers, ['Department', 'Budget']);
      expect(sheet2.rows.length, 1);
      expect(sheet2.rows[0]['department'], 'Engineering');
      expect(sheet2.rows[0]['budget'], 50000);
    });

    test('Extracts rich-text formatted runs from shared strings', () {
      final sheetXml =
          '''<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">
  <sheetData>
    <row r="1">
      <c r="A1" t="s"><v>0</v></c>
    </row>
    <row r="2">
      <c r="A2" t="s"><v>1</v></c>
    </row>
  </sheetData>
</worksheet>''';

      final sharedStringsXml =
          '''<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<sst xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" count="2" uniqueCount="2">
  <si><t>Header Title</t></si>
  <si>
    <r><rPr><b/></rPr><t>Bold </t></r>
    <r><t>and </t></r>
    <r><rPr><i/></rPr><t>Italic</t></r>
  </si>
</sst>''';

      final workbookXml =
          '''<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<workbook xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">
  <sheets><sheet name="RichText" sheetId="1" r:id="rId1"/></sheets>
</workbook>''';

      final relsXml = '''<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">
  <Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/worksheet" Target="worksheets/sheet1.xml"/>
</Relationships>''';

      final archive = Archive();
      archive.addFile(
        ArchiveFile(
          'xl/workbook.xml',
          workbookXml.length,
          utf8.encode(workbookXml),
        ),
      );
      archive.addFile(
        ArchiveFile(
          'xl/_rels/workbook.xml.rels',
          relsXml.length,
          utf8.encode(relsXml),
        ),
      );
      archive.addFile(
        ArchiveFile(
          'xl/sharedstrings.xml',
          sharedStringsXml.length,
          utf8.encode(sharedStringsXml),
        ),
      );
      archive.addFile(
        ArchiveFile(
          'xl/worksheets/sheet1.xml',
          sheetXml.length,
          utf8.encode(sheetXml),
        ),
      );

      final zipBytes = Uint8List.fromList(ZipEncoder().encode(archive));
      final wb = AiGridExcelParser.parseBytes(zipBytes);
      final sheet = wb.primarySheet!;

      expect(sheet.headers.first, 'Header Title');
      expect(sheet.rows.first['header_title'], 'Bold and Italic');
    });

    test('Correctly handles sparse cells and coordinate mapping', () {
      final sheetXml =
          '''<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">
  <sheetData>
    <row r="1">
      <c r="A1" t="inlineStr"><is><t>Col A</t></is></c>
      <c r="C1" t="inlineStr"><is><t>Col C</t></is></c>
    </row>
    <row r="2">
      <c r="A2"><v>100</v></c>
      <c r="C2"><v>300</v></c>
    </row>
  </sheetData>
</worksheet>''';

      final workbookXml =
          '''<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<workbook xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">
  <sheets><sheet name="Sparse" sheetId="1" r:id="rId1"/></sheets>
</workbook>''';

      final relsXml = '''<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">
  <Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/worksheet" Target="worksheets/sheet1.xml"/>
</Relationships>''';

      final archive = Archive();
      archive.addFile(
        ArchiveFile(
          'xl/workbook.xml',
          workbookXml.length,
          utf8.encode(workbookXml),
        ),
      );
      archive.addFile(
        ArchiveFile(
          'xl/_rels/workbook.xml.rels',
          relsXml.length,
          utf8.encode(relsXml),
        ),
      );
      archive.addFile(
        ArchiveFile(
          'xl/worksheets/sheet1.xml',
          sheetXml.length,
          utf8.encode(sheetXml),
        ),
      );

      final zipBytes = Uint8List.fromList(ZipEncoder().encode(archive));
      final wb = AiGridExcelParser.parseBytes(zipBytes);

      final sheet = wb.primarySheet!;
      expect(sheet.headers.length, 3);
      expect(sheet.headers[0], 'Col A');
      expect(sheet.headers[1], 'Column_B'); // auto-filled sparse header
      expect(sheet.headers[2], 'Col C');

      expect(sheet.rows[0]['col_a'], 100);
      expect(sheet.rows[0]['column_b'], '');
      expect(sheet.rows[0]['col_c'], 300);
    });
  });

  group('AiGrid Excel MCP Tools Tests', () {
    test(
      'grid_import_excel inspects multi-sheet workbook without loading',
      () async {
        final controller = AiGridController();
        final tool = GridImportExcelTool(controller);

        final zipBytes = buildMockMultiSheetExcelBytes();
        final base64Str = base64Encode(zipBytes);

        final result = await tool.execute({
          'base64': base64Str,
          'inspectOnly': true,
        });

        expect(result.isError, isFalse);
        final data =
            jsonDecode(result.content.first.text!) as Map<String, dynamic>;
        expect(data['sheetCount'], 2);
        final sheets = data['sheets'] as List;
        expect(sheets.length, 2);
        expect(sheets[0]['name'], 'Quarterly Sales');
        expect(sheets[1]['name'], 'Annual Targets');
      },
    );

    test(
      'grid_import_excel imports targeted sheet and loads dynamic datasource',
      () async {
        final controller = AiGridController();
        final tool = GridImportExcelTool(controller);

        final zipBytes = buildMockMultiSheetExcelBytes();
        final base64Str = base64Encode(zipBytes);

        final result = await tool.execute({
          'base64': base64Str,
          'sheetName': 'Annual Targets',
        });

        expect(result.isError, isFalse);
        final data =
            jsonDecode(result.content.first.text!) as Map<String, dynamic>;
        expect(data['status'], 'success');
        expect(data['sheet'], 'Annual Targets');
        expect(data['rowCount'], 1);

        // Verify controller state updated
        expect(controller.activeDynamicDatasource, isNotNull);
        expect(controller.columns.length, 2);
        expect(
          controller.columns.map((c) => c.field),
          containsAll(['department', 'budget']),
        );
      },
    );
  });

  group('AiGridExcelSheetPickerDialog Widget Tests', () {
    testWidgets('Renders worksheets and switches selection on tap', (
      tester,
    ) async {
      tester.view.physicalSize = const Size(1024, 768);
      tester.view.devicePixelRatio = 1.0;
      addTearDown(tester.view.resetPhysicalSize);
      addTearDown(tester.view.resetDevicePixelRatio);

      final zipBytes = buildMockMultiSheetExcelBytes();
      final workbook = AiGridExcelParser.parseBytes(
        zipBytes,
        fileName: 'enterprise.xlsx',
      );

      AiGridExcelSheet? selectedResult;

      await tester.pumpWidget(
        MaterialApp(
          home: Scaffold(
            body: Builder(
              builder: (context) => ElevatedButton(
                onPressed: () async {
                  selectedResult = await AiGridExcelSheetPickerDialog.show(
                    context,
                    workbook: workbook,
                  );
                },
                child: const Text('Open Picker'),
              ),
            ),
          ),
        ),
      );

      // Click button to open dialog
      await tester.tap(find.text('Open Picker'));
      await tester.pumpAndSettle();

      // Check dialog elements
      expect(find.text('enterprise.xlsx'), findsOneWidget);
      expect(find.text('Quarterly Sales'), findsWidgets);
      expect(find.text('Annual Targets'), findsWidgets);

      // Tap on second sheet "Annual Targets"
      await tester.tap(find.text('Annual Targets').first);
      await tester.pumpAndSettle();

      // Tap import button
      expect(find.text('Import "Annual Targets"'), findsOneWidget);
      await tester.tap(find.text('Import "Annual Targets"'));
      await tester.pumpAndSettle();

      // Check returned sheet
      expect(selectedResult, isNotNull);
      expect(selectedResult!.name, 'Annual Targets');
    });
  });
